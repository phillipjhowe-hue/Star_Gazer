#!/usr/bin/env python3
"""Builds src/data.js from the d3-celestial data files.

Usage: python3 tools/build_data.py <path-to-d3-celestial/data>
"""
import json
import os
import sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), "..", "data.js")


def load(name):
    with open(os.path.join(src, name), encoding="utf-8") as f:
        return json.load(f)


def ra(x):
    return round(x % 360, 3)


names = load("starnames.json")
stars = []
for f in load("stars.6.json")["features"]:
    lon, lat = f["geometry"]["coordinates"]
    p = f["properties"]
    try:
        bv = round(float(p.get("bv") or 0.6), 2)
    except ValueError:
        bv = 0.6
    n = names.get(str(f["id"]), {})
    proper = n.get("name", "")
    desig = ""
    if n.get("desig") and n.get("c"):
        desig = n["desig"] + " " + n["c"]
    stars.append([ra(lon), round(lat, 3), round(p["mag"], 2), bv, proper, desig])
stars.sort(key=lambda s: s[2])

lines = {}
for f in load("constellations.lines.json")["features"]:
    lines[f["id"]] = [[[ra(a), round(b, 3)] for a, b in seg] for seg in f["geometry"]["coordinates"]]

cons = []
for f in load("constellations.json")["features"]:
    p = f["properties"]
    lon, lat = f["geometry"]["coordinates"]
    cons.append({"id": f["id"], "name": p["name"], "gen": p.get("gen", ""),
                 "rank": int(p.get("rank", 3)), "ra": ra(lon), "dec": round(lat, 2)})

bounds = {}
for f in load("constellations.bounds.json")["features"]:
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    rings = [[[ra(a), round(b, 2)] for a, b in ring] for poly in polys for ring in poly]
    bounds.setdefault(f["id"], []).extend(rings)

import subprocess
mw = subprocess.run([sys.executable, os.path.join(os.path.dirname(__file__), "build_milkyway.py"), src],
                    capture_output=True, text=True, check=True).stdout.strip()

with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_data.py from d3-celestial data (BSD-3-Clause, Olaf Frohn)\n")
    f.write("// stars: [raDeg, decDeg, mag, B-V, properName, designation]\n")
    f.write("const STARS=" + json.dumps(stars, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("const CON_LINES=" + json.dumps(lines, separators=(",", ":")) + ";\n")
    f.write("const CON_BOUNDS=" + json.dumps(bounds, separators=(",", ":")) + ";\n")
    f.write("// Milky Way: [raDeg, decDeg, intensity 0-1]\n")
    f.write("const MILKY_WAY=" + mw + ";\n")
    f.write("const CONSTELLATIONS=" + json.dumps(cons, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("stars", len(stars), "constellations", len(cons), "bytes", os.path.getsize(out))
